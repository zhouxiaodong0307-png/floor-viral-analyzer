'use strict';
const assert=require('node:assert/strict');
const {chromium}=require('playwright');
const site='https://muye-guan-jia-migration-test.onrender.com/';
const ipadUA='Mozilla/5.0 (iPad; CPU OS 18_7 like Mac OS X) AppleWebKit/605.1.15 (KHTML, like Gecko) Version/18.7 Mobile/15E148 Safari/604.1';
const close=(x,y,t=8)=>Math.abs(x-y)<=t;
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 try{
  for(const width of [768,1024,1180]){
   const context=await browser.newContext({viewport:{width,height:1024},userAgent:ipadUA,hasTouch:true,isMobile:true,locale:'zh-CN'});
   const page=await context.newPage(),errors=[];
   page.on('pageerror',e=>errors.push(e.message));
   const res=await page.goto(site,{waitUntil:'domcontentloaded',timeout:90000});
   assert.ok(res?.ok(),'test site should load');
   await page.waitForFunction(()=>window.muyeIPadNumericV412?.enabled&&typeof addMeasureRow==='function',{timeout:25000});
   const safe=await page.evaluate(()=>({version:APP_VERSION,cloud:SUPABASE_URL,auth:FLOOR_AUTH_MODE,writable:isCloudWritableRuntime()}));
   assert.deepEqual(safe,{version:'415',cloud:'',auth:'disabled',writable:false});
   await page.evaluate(()=>{
     show('quote');addMeasureRow('resize simulation','');
     document.querySelector('.measure-row:last-child .mexpr')?.scrollIntoView({block:'center'});
   });
   const field=page.locator('.measure-row .mexpr').last();
   await field.tap();
   const pad=page.locator('#muye-ipad-numeric-v412');
   const handle=page.locator('#muye-ipad-numeric-v412 .muye-ipad-pad-resize');
   assert.ok(await pad.isVisible());
   assert.ok(await handle.isVisible());
   let first=await pad.boundingBox();
   assert.ok(first.width>=440&&first.height>=475,'expected a usable default keypad');
   const grip=await handle.boundingBox();
   await page.mouse.move(grip.x+grip.width*.7,grip.y+grip.height*.7);
   await page.mouse.down();
   await page.mouse.move(grip.x-640,grip.y-640,{steps:10});
   await page.mouse.up();
   const smallest=await pad.boundingBox();
   assert.ok(close(smallest.width,445,3),'minimum width respected: '+JSON.stringify(smallest));
   assert.ok(close(smallest.height,480,3),'minimum height respected: '+JSON.stringify(smallest));
   assert.ok(smallest.x>=0&&smallest.y>=0,'minimum size remains in viewport');
   const session=await context.newCDPSession(page);
   const q=await handle.boundingBox();
   let tx=q.x+q.width*.6,ty=q.y+q.height*.6;
   await session.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:tx,y:ty}]});
   await session.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:tx+110,y:ty+77}]});
   await session.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
   const enlarged=await pad.boundingBox();
   assert.ok(enlarged.width>smallest.width+65,'touch resizing width should work: '+JSON.stringify({smallest,enlarged}));
   assert.ok(enlarged.height>smallest.height+43,'touch resizing height should work');
   await page.locator('#muye-ipad-numeric-v412 button[data-key="3"]').tap();
   await page.locator('#muye-ipad-numeric-v412 button[data-key="0"]').tap();
   await page.locator('#muye-ipad-numeric-v412 button[data-key="0"]').tap();
   await page.locator('#muye-ipad-numeric-v412 button[data-key="×"]').tap();
   await page.locator('#muye-ipad-numeric-v412 button[data-key="4"]').tap();
   await page.locator('#muye-ipad-numeric-v412 button[data-key="0"]').tap();
   await page.locator('#muye-ipad-numeric-v412 button[data-key="0"]').tap();
   assert.equal(await field.inputValue(),'300×400','resized keypad should calculate dimensions');
   assert.equal(await page.evaluate(()=>parseMeasureExpr(document.querySelectorAll('.measure-row .mexpr')[document.querySelectorAll('.measure-row .mexpr').length-1].value)),12);
   const header=page.locator('#muye-ipad-numeric-v412 .muye-ipad-pad-drag');
   let h=await header.boundingBox(),pos=await pad.boundingBox();
   await page.mouse.move(h.x+h.width*.5,h.y+h.height*.5);
   await page.mouse.down();
   await page.mouse.move(h.x+h.width*.5+30,h.y+h.height*.5-45,{steps:8});
   await page.mouse.up();
   const shifted=await pad.boundingBox();
   assert.ok(Math.abs(shifted.x-pos.x)>12||Math.abs(shifted.y-pos.y)>12,'drag header must still work');
   assert.ok(close(shifted.width,enlarged.width,3)&&close(shifted.height,enlarged.height,3),'moving must not resize');
   const prefs=await page.evaluate(()=>({stored:JSON.parse(localStorage.getItem('muye-ipad-keypad-layout-v414')),status:muyeIPadNumericV412.status(),orderData:localStorage.getItem('floor_orders_v3')}));
   assert.equal(prefs.status.resizable,true);
   assert.ok(prefs.stored?.width>=440&&prefs.stored?.height>=475);
   await pad.locator('[data-action="done"]').tap();assert.equal(await pad.isVisible(),false);
   await field.tap();
   const reopened=await pad.boundingBox();
   assert.ok(close(reopened.width,shifted.width,3)&&close(reopened.height,shifted.height,3),'size should persist on reopen');
   await page.reload({waitUntil:'domcontentloaded'});
   await page.waitForFunction(()=>window.muyeIPadNumericV412?.enabled,{timeout:20000});
   await page.evaluate(()=>{show('quote');addMeasureRow('reload test','')});
   await page.locator('.measure-row .mexpr').last().tap();
   const reloadSize=await pad.boundingBox();
   assert.ok(close(reloadSize.width,reopened.width,3)&&close(reloadSize.height,reopened.height,3),'local size preference persists after reload');
   await page.setViewportSize({width:width===768?1024:768,height:540});
   await page.waitForTimeout(180);
   const v=await page.evaluate(()=>({width:window.innerWidth,height:window.innerHeight,scroll:document.documentElement.scrollWidth}));
   const rotated=await pad.boundingBox();
   assert.ok(rotated.x>=-1&&rotated.y>=-1,'after rotation panel stays onscreen');
   assert.ok(rotated.x+rotated.width<=v.width+2&&rotated.y+rotated.height<=v.height+2,'panel fully visible after rotation');
   assert.ok(v.scroll<=v.width+2,'panel cannot expand document width');
   assert.deepEqual(errors,[],'unexpected Javascript errors');
   console.log('PASS V414 iPad resizing+dragging+number input+storage+rotation viewport '+width);
   await context.close();
  }
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1});
